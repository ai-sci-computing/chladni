/**
 * @file test_lme_ss_plate.cpp
 * @brief Simply-supported square plate biharmonic eigenvalues — LME
 *        validation against Navier's analytic solution.
 *
 * Migrated 2026-05-29 from the flat path to the CURVED path (ghost-off) —
 * the formulation the GUI's LME tab actually runs — so the test mirrors the
 * app. The curved value-based-truncation bending operator gives ~2.1% here
 * (vs the flat path's 0.35%); 1st-order LME still converges on the
 * biharmonic, the verdict below.
 *
 * This is **the decision point** for the 1st-order LME formulation:
 *
 *  - **Strang--Fix gives a sufficient, not necessary, condition.** For
 *    H² convergence on a 4th-order PDE the textbook requirement is
 *    polynomial reproduction of degree m ≥ 2; our 1st-order LME only
 *    reaches m = 1. The empirical claim (Rosolen 2013 abstract) is that
 *    1st-order LME with wide enough support still converges on the
 *    biharmonic in the meshfree regime. This test is what tells us
 *    whether that claim survives our implementation.
 *
 *  - **If it converges cleanly here**, the LMEAssembler is validated
 *    on its primary problem and we can proceed to the existing
 *    analytic fixtures (annulus, free-edge circular plate, Chladni
 *    free-edge square). If it stalls, the implementation plan §10
 *    step 6 calls for falling back to 2nd-order SME (Rosolen 2013).
 *
 * Navier analytic for SS rectangular plate (uniform thickness):
 * @f[
 *     \omega_{mn}^2 \;=\; \pi^4\,
 *                          \bigl( m^2/a^2 + n^2/b^2 \bigr)^2
 *                          \,\frac{D}{\rho h},
 *     \qquad m, n = 1, 2, 3, \ldots .
 * @f]
 *
 * Fixture: unit-square plate generated by @ref chladni::mesh::generate_flat_plate.
 * The two-corner chamfering it applies (mesh.cpp:269-291) leaves the
 * conv-hull boundary slightly non-square — at the resolutions used
 * here the missing-corner-triangle area is ~1% of the plate, well
 * below the LME discretisation error.
 *
 * Material: D = 1, ρh = 1, ν = 0.3 (unit fixture; analytic
 * eigenvalues are π^4 (m²/a² + n²/b²)² directly).
 *
 * BC enforcement: hard-pin every boundary-vertex z-DOF (w = 0 on ∂Ω);
 * the LME basis weak Kronecker-delta on boundary edges (interior-node
 * basis functions vanish there in the limit) gives w ≡ 0 on the
 * boundary curve to within the basis tail. The in-plane DOFs (x, y)
 * are pinned to zero everywhere — the assembler ships three 3-tiled
 * copies of the scalar Kirchhoff matrices, and we only want the
 * physical z-spectrum.
 */

#include <chladni/mesh.hpp>
#include <chladni/shell.hpp>
#include <chladni/shell/lme.hpp>

#include "lme_test_helpers.hpp"

#include <catch2/catch_test_macros.hpp>
